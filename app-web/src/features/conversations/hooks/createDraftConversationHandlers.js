import { createDraftLifecycleHandlers } from './draft-handlers/draft-lifecycle.js';
import { createDraftMaterializeHandlers } from './draft-handlers/draft-materialize.js';
import { createTaskRuntimeRestoreHandlers } from './draft-handlers/task-runtime-restore.js';
import { createTaskControlHandlers } from './draft-handlers/task-control.js';

export function createDraftConversationHandlers(ctx) {
  const {
    API_BASE,
    DEFAULT_SESSION_NAME,
    applyConversationSnapshot,
    apiFetch,
    applyContextUsage,
    buildApiHeaders,
    chatFinalizedTaskIdsRef,
    conversationActivationSeqRef,
    conversationDetailAbortRef,
    conversationId,
    conversationIdRef,
    createConversationInProject,
    createDefaultProject,
    createEmptyTaskRuntimeState,
    detachActiveRunFromCurrentConversation,
    draftConversationIdsRef,
    draftConversationRef,
    draftFirstSendRef,
    draftServerCreateRef,
    flushRuntimeTasksToWorkspace,
    generateHexId,
    getRuntime,
    isTaskActuallyActive,
    latestContextUsageFromTasks,
    mutateRuntime,
    normalizeWorkspaceOrdering,
    normalizeRuntimeEvents,
    pendingCreatedDetailRef,
    rekeyChatDraft,
    resetContextUsage,
    runtimesRef,
    setComposerAttachment,
    setConversationAttachments,
    setConversationError,
    setConversationId,
    setConversationReady,
    setLocalWorkspace,
    setStoredConversationId,
    setUploadState,
    setWorkspaceState,
    taskDetailToRuntimeTask,
    taskRuntimeEventCacheRef,
    taskRuntimeFetchesRef,
    taskUpdatedTimestamp,
    updateTaskRuntimeState,
    userCancelledTaskIdsRef,
    viewModeRef,
    workspaceState,
    workspaceStateWithConversationDetail,
  } = ctx;

  // 跨域用到的那两个函数显式递给 materialize：模块之间互相 import 会成环。
  const lifecycle = createDraftLifecycleHandlers({
    API_BASE,
    DEFAULT_SESSION_NAME,
    apiFetch,
    conversationActivationSeqRef,
    conversationDetailAbortRef,
    conversationIdRef,
    createDefaultProject,
    createEmptyTaskRuntimeState,
    detachActiveRunFromCurrentConversation,
    draftConversationIdsRef,
    draftConversationRef,
    draftFirstSendRef,
    flushRuntimeTasksToWorkspace,
    generateHexId,
    mutateRuntime,
    normalizeWorkspaceOrdering,
    pendingCreatedDetailRef,
    rekeyChatDraft,
    resetContextUsage,
    runtimesRef,
    setComposerAttachment,
    setConversationAttachments,
    setConversationError,
    setConversationId,
    setConversationReady,
    setLocalWorkspace,
    setStoredConversationId,
    setUploadState,
    setWorkspaceState,
    viewModeRef,
    workspaceState,
  });

  const materialize = createDraftMaterializeHandlers({
    applyConversationSnapshot,
    clearDraftFirstSendInFlight: lifecycle.clearDraftFirstSendInFlight,
    conversationActivationSeqRef,
    conversationId,
    conversationIdRef,
    createConversationInProject,
    draftConversationIdsRef,
    draftConversationRef,
    draftFirstSendRef,
    draftServerCreateRef,
    getRuntime,
    isConversationActivationCurrent: lifecycle.isConversationActivationCurrent,
    pendingCreatedDetailRef,
    rekeyChatDraft,
    runtimesRef,
    setConversationId,
    setStoredConversationId,
    setWorkspaceState,
    viewModeRef,
    workspaceState,
    workspaceStateWithConversationDetail,
  });

  const restore = createTaskRuntimeRestoreHandlers({
    API_BASE,
    apiFetch,
    applyContextUsage,
    buildApiHeaders,
    getRuntime,
    isTaskActuallyActive,
    latestContextUsageFromTasks,
    normalizeRuntimeEvents,
    taskDetailToRuntimeTask,
    taskRuntimeEventCacheRef,
    taskRuntimeFetchesRef,
    updateTaskRuntimeState,
  });

  const control = createTaskControlHandlers({
    API_BASE,
    apiFetch,
    buildApiHeaders,
    chatFinalizedTaskIdsRef,
    getRuntime,
    isTaskActuallyActive,
    mutateRuntime,
    runtimesRef,
    taskUpdatedTimestamp,
    updateTaskRuntimeState,
    userCancelledTaskIdsRef,
  });

  // 返回对象形状（字段名与顺序）是 AppShell 的装配契约，别重排。
  return {
    invalidateConversationActivation: lifecycle.invalidateConversationActivation,
    isConversationActivationCurrent: lifecycle.isConversationActivationCurrent,
    isDraftConversationId: lifecycle.isDraftConversationId,
    clearDraftConversationState: lifecycle.clearDraftConversationState,
    openDraftConversation: lifecycle.openDraftConversation,
    ensureServerConversationForActiveDraft: materialize.ensureServerConversationForActiveDraft,
    markDraftConversationKept: lifecycle.markDraftConversationKept,
    markDraftFirstSendInFlight: lifecycle.markDraftFirstSendInFlight,
    clearDraftFirstSendInFlight: lifecycle.clearDraftFirstSendInFlight,
    isDraftFirstSendInFlight: lifecycle.isDraftFirstSendInFlight,
    materializeDraftConversationForSend: materialize.materializeDraftConversationForSend,
    fetchTaskRuntimeDetail: restore.fetchTaskRuntimeDetail,
    fetchTaskRuntimeBatch: restore.fetchTaskRuntimeBatch,
    restoreTaskRuntimes: restore.restoreTaskRuntimes,
    restoreLatestTaskRuntime: restore.restoreLatestTaskRuntime,
    cancelActiveTask: control.cancelActiveTask,
    queueTaskInput: control.queueTaskInput,
    cancelActiveConversationTask: control.cancelActiveConversationTask,
    stopConversationRuntimeBeforeDelete: control.stopConversationRuntimeBeforeDelete,
  };
}
